export const getTeamBySlug = (slug) => teams.find((team) => team.slug === slug)

export const getTeamInitials = (name) => name
  .split(/\s+/)
  .filter(Boolean)
  .slice(0, 2)
  .map((word) => word[0])
  .join('')
  .toUpperCase()
